PAL = {"k": "#000000", "D": "#404040", "g": "#808080", "s": "#c0c0c0", "w": "#ffffff", "y": "#ffff00",
       "o": "#c08000", "r": "#ff0000", "R": "#800000", "n": "#000080", "b": "#0000ff", "c": "#00ffff",
       "C": "#008080", "G": "#008000", "l": "#00ff00"}


def rows(name):
    r = [x for x in ICONS[name].strip("\n").split("\n")]
    r = (r + ["." * 16] * 16)[:16]
    return [(x + "." * 16)[:16] for x in r]


def check():
    for n in ICONS:
        raw = [x for x in ICONS[n].strip("\n").split("\n")]
        bad = [i for i, x in enumerate(raw) if len(x) != 16]
        if len(raw) != 16 or bad:
            print("icon %s: %d rows, bad widths at %s" % (n, len(raw), bad))


def qml_data():
    import json
    return json.dumps({n: "".join(rows(n)) for n in ICONS}, separators=(",", ":"))


def png(name, out, scale=2, accent="#2a5ea8", accent2="#6a9ee8"):
    from PIL import Image
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    px = img.load()
    pal = dict(PAL, a=accent, A=accent2)
    for y, r in enumerate(rows(name)):
        for x, ch in enumerate(r):
            if ch in pal:
                c = pal[ch].lstrip("#")
                px[x, y] = (int(c[0:2], 16), int(c[2:4], 16), int(c[4:6], 16), 255)
    img.resize((16 * scale, 16 * scale), Image.NEAREST).save(out)


