// text → lines of block characters. style: block (█) | shade (▓░) | hash (#) | dots (•)
function render(text, style) {
    var on = style === "hash" ? "#" : (style === "dots" ? "•" : (style === "shade" ? "▓" : "█"));
    var off = style === "shade" ? "░" : " ";
    var out = [];
    var lines = String(text || "").toUpperCase().split("\n");
    for (var l = 0; l < lines.length; l++) {
        var rows = ["", "", "", "", ""];
        var s = lines[l];
        for (var i = 0; i < s.length; i++) {
            var g = G[s[i]] || G[" "];
            for (var r = 0; r < 5; r++) {
                rows[r] += g[r].replace(/#/g, on).replace(/\./g, off) + (i < s.length - 1 ? off : "");
            }
        }
        if (l > 0) out.push("");
        out = out.concat(rows);
    }
    return out.join("\n");
}
